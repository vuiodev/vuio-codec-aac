//! Spectral band replication: Huffman codebooks and band-layout tables.
//!
//! The ten codebooks of ISO/IEC 14496-3 Table 4.A.76 and following, stored in the
//! canonical form a decoder wants rather than as code/length pairs: symbols ordered
//! by code length then by code, with the first code and symbol index of each length
//! alongside. Decoding is then a walk down the lengths, one bit at a time, with a
//! comparison per length and no table search.
//!
//! Every book here was checked at build time to be prefix-free and canonical; the
//! tests below re-derive each code from the tables and compare against the
//! reference values.

use crate::bitstream::BitReader;
use crate::error::{DecodeError, Result};

/// Longest code any SBR book contains.
pub const SBR_MAX_CODE_BITS: usize = 20;

/// One SBR Huffman codebook in canonical form.
#[derive(Debug, Clone, Copy)]
pub struct SbrCodebook {
    /// Length of the longest code.
    max_len: u8,
    /// Numeric value of the first code of each length, indexed by length.
    first_code: &'static [u32; SBR_MAX_CODE_BITS + 1],
    /// Index into `symbols` of the first symbol of each length.
    first_symbol: &'static [u16; SBR_MAX_CODE_BITS + 1],
    /// How many codes have each length.
    count: &'static [u16; SBR_MAX_CODE_BITS + 1],
    /// Symbols, ordered by code length and then by code.
    symbols: &'static [i8],
}

impl SbrCodebook {
    /// Read one symbol.
    ///
    /// Codes run from 2 to 19 bits, so the loop is bounded and a corrupt stream
    /// falls out of it rather than spinning.
    pub fn decode(&self, reader: &mut BitReader) -> Result<i32> {
        let mut code = 0u32;
        for len in 1..=self.max_len as usize {
            code = (code << 1) | u32::from(reader.read_bit()?);
            let count = u32::from(self.count[len]);
            if count > 0 {
                let first = self.first_code[len];
                if code >= first && code - first < count {
                    let at = self.first_symbol[len] as usize + (code - first) as usize;
                    return Ok(i32::from(self.symbols[at]));
                }
            }
        }
        Err(DecodeError::CorruptedFrame("no SBR Huffman code matched".into()).into())
    }
}

