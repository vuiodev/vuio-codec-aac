mod tests {
    use super::*;
    use crate::bitstream::BitWriter;

    /// Every book, paired with the reference code and length tables it came from.
    #[allow(clippy::type_complexity)]
    fn books() -> Vec<(&'static SbrCodebook, &'static [u32], &'static [u8], i32)> {
        vec![
    (&ENV_LEVEL_1_5_TIME, &V_HUFF_ENV_LVL_C10T_CODES[..], &V_HUFF_ENV_LVL_C10T_LENGTHS[..], 60),
    (&ENV_LEVEL_1_5_FREQ, &V_HUFF_ENV_LVL_C10F_CODES[..], &V_HUFF_ENV_LVL_C10F_LENGTHS[..], 60),
    (&ENV_BALANCE_1_5_TIME, &BOOK_SBR_ENV_BAL_C10T_CODES[..], &BOOK_SBR_ENV_BAL_C10T_LENGTHS[..], 24),
    (&ENV_BALANCE_1_5_FREQ, &BOOK_SBR_ENV_BAL_C10F_CODES[..], &BOOK_SBR_ENV_BAL_C10F_LENGTHS[..], 24),
    (&ENV_LEVEL_3_0_TIME, &V_HUFF_ENV_LVL_C11T_CODES[..], &V_HUFF_ENV_LVL_C11T_LENGTHS[..], 31),
    (&ENV_LEVEL_3_0_FREQ, &V_HUFF_ENV_LVL_C11F_CODES[..], &V_HUFF_ENV_LVL_C11F_LENGTHS[..], 31),
    (&ENV_BALANCE_3_0_TIME, &BOOK_SBR_ENV_BAL_C11T_CODES[..], &BOOK_SBR_ENV_BAL_C11T_LENGTHS[..], 12),
    (&ENV_BALANCE_3_0_FREQ, &BOOK_SBR_ENV_BAL_C11F_CODES[..], &BOOK_SBR_ENV_BAL_C11F_LENGTHS[..], 12),
    (&NOISE_LEVEL_3_0_TIME, &V_HUFF_NOISE_LVL_C11T_CODES[..], &V_HUFF_NOISE_LVL_C11T_LENGTHS[..], 31),
    (&NOISE_BALANCE_3_0_TIME, &BOOK_SBR_NOISE_BAL_C11T_CODES[..], &BOOK_SBR_NOISE_BAL_C11T_LENGTHS[..], 12),
        ]
    }

    /// Writing each reference code and reading it back must return the symbol that
    /// code stands for. This is the property the canonical rearrangement has to
    /// preserve, and it checks every symbol of every book.
    #[test]
    fn every_code_round_trips_to_its_symbol() {
        for (book, codes, lengths, lav) in books() {
            for (i, (&code, &len)) in codes.iter().zip(lengths.iter()).enumerate() {
                let mut writer = BitWriter::new();
                writer.write_bits(u64::from(code), len as usize);
                // Pad so the reader never runs dry mid-code.
                writer.write_bits(0, 24);
                let bytes = writer.into_bytes();
                let mut reader = BitReader::new(&bytes);
                let got = book.decode(&mut reader).unwrap();
                assert_eq!(got, i as i32 - lav, "symbol {i} of a book decoded wrong");
                assert_eq!(reader.bit_position(), len as usize, "code length wrong");
            }
        }
    }

    /// No code may be a prefix of another, or the reader would stop early.
    #[test]
    fn books_are_prefix_free() {
        for (_, codes, lengths, _) in books() {
            for i in 0..codes.len() {
                for j in 0..codes.len() {
                    if lengths[i] >= lengths[j] {
                        continue;
                    }
                    let shifted = codes[j] >> (lengths[j] - lengths[i]);
                    assert_ne!(shifted, codes[i], "code {i} prefixes code {j}");
                }
            }
        }
    }
}
