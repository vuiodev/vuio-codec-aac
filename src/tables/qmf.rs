/// Sign the polyphase fold applies to the tap block containing `n`.
///
/// The filterbank sums taps `n`, `n + 2M`, `n + 4M`, ... into one accumulator before
/// modulating, which is only valid because the modulation's own factor over that
/// stride is `(-1)^j`. Folding that alternation into the window instead is what
/// turns each accumulator into a plain DFT input; it is also why the reference
/// implementation's fixed-point table carries these sign flips baked in.
const fn fold_sign(n: usize) -> f32 {
    if (n / 128).is_multiple_of(2) { 1.0 } else { -1.0 }
}

/// Build the window the synthesis bank applies, `c[n]` with the polyphase fold.
const fn folded() -> [f32; QMF_FILTER_LENGTH] {
    let mut out = [0.0; QMF_FILTER_LENGTH];
    let mut n = 0;
    while n < QMF_FILTER_LENGTH {
        out[n] = QMF_PROTOTYPE[n] * fold_sign(n);
        n += 1;
    }
    out
}

/// Build the window the analysis bank applies, the even taps with the fold.
const fn folded_decimated() -> [f32; QMF_FILTER_LENGTH / 2] {
    let mut out = [0.0; QMF_FILTER_LENGTH / 2];
    let mut n = 0;
    while n < QMF_FILTER_LENGTH / 2 {
        out[n] = QMF_PROTOTYPE[2 * n] * fold_sign(2 * n);
        n += 1;
    }
    out
}

/// The 640-tap window the 64-band synthesis bank applies.
pub static QMF_SYNTHESIS_WINDOW: [f32; QMF_FILTER_LENGTH] = folded();

/// The 320-tap window the 32-band analysis bank applies, and the 32-band synthesis
/// bank with it.
pub static QMF_ANALYSIS_WINDOW: [f32; QMF_FILTER_LENGTH / 2] = folded_decimated();

#[cfg(test)]
mod tests {
    use super::*;

    /// The prototype is a linear-phase filter, so it must be symmetric about tap 320.
    #[test]
    fn prototype_is_symmetric() {
        for n in 1..QMF_FILTER_LENGTH {
            assert_eq!(
                QMF_PROTOTYPE[n], QMF_PROTOTYPE[QMF_FILTER_LENGTH - n],
                "tap {n} breaks symmetry"
            );
        }
    }

    /// The decimated table must be exactly the even taps of the full one.
    #[test]
    fn decimated_matches_even_taps() {
        for n in 0..QMF_FILTER_LENGTH / 2 {
            assert_eq!(QMF_PROTOTYPE_DECIMATED[n], QMF_PROTOTYPE[2 * n]);
        }
    }

    /// The folded windows differ from the prototype only in sign, and the fold
    /// pattern is the one the reference implementation's table carries.
    #[test]
    fn folded_windows_differ_only_in_sign() {
        for n in 0..QMF_FILTER_LENGTH {
            assert_eq!(QMF_SYNTHESIS_WINDOW[n].abs(), QMF_PROTOTYPE[n].abs());
            let flipped = QMF_SYNTHESIS_WINDOW[n] != QMF_PROTOTYPE[n];
            let expected = (128..256).contains(&n) || (384..512).contains(&n);
            assert_eq!(flipped, expected && QMF_PROTOTYPE[n] != 0.0, "tap {n}");
        }
        for n in 0..QMF_FILTER_LENGTH / 2 {
            assert_eq!(QMF_ANALYSIS_WINDOW[n], QMF_SYNTHESIS_WINDOW[2 * n]);
        }
    }

    /// Peak sits at the centre tap and the filter is a lowpass, so every tap is
    /// bounded by it.
    #[test]
    fn peak_is_the_centre_tap() {
        let peak = QMF_PROTOTYPE[320];
        assert!((peak - 0.853_738_56).abs() < 1e-7);
        assert!(QMF_PROTOTYPE.iter().all(|&v| v.abs() <= peak));
    }
}
