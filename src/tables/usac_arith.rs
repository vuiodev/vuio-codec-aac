//! Context-adaptive spectral arithmetic coding for MPEG-D USAC (ISO/IEC
//! 23003-3), ported from `c/libxaac/decoder/ixheaacd_arith_dec.c` and
//! `c/libxaac/encoder/iusace_arith_enc.c`.
//!
//! USAC replaces classic AAC's Huffman spectral coding with a single adaptive
//! arithmetic coder shared by both the frequency-domain and TCX paths. Every
//! coefficient pair `(a, b)` is coded through a *context*: a running hash of the
//! last few decoded magnitudes, both at this frequency position in the previous
//! block ([`Contexts`] calls this `prev`) and immediately before it in this block
//! (`pres`). The context selects one of 64 cumulative-frequency rows in
//! [`ARI_CF_M`] via [`context_pk`], so quiet, steady regions get a sharply peaked
//! model (cheap zeros) and busy regions get a flatter one, without transmitting a
//! single side-information bit for it — both encoder and decoder derive the same
//! context from data they have already coded.
//!
//! A magnitude too large for the 0..15 symbol range escapes: the coder emits
//! [`ESCAPE`] and repeats one bit-plane of both `a` and `b` (via [`ARI_CF_R`],
//! keyed by which of the two is already zero) before trying again one bit
//! narrower, shifting the context by `esc_nb << 17` each round so deeper escapes
//! draw from their own model rows. Sign is not modeled at all — since a coded
//! magnitude's sign carries roughly one bit of information regardless of context,
//! it is sent as a single raw bit per nonzero coefficient after the arithmetic
//! payload, rather than spending model rows on it.
//!
//! These tables and [`context_pk`]'s search are identical between the libxaac
//! encoder and decoder (verified by direct comparison while porting) — the
//! contract only holds if both sides agree on every entry, so treat this file as
//! a fixed constant, not something to renumber for readability.

/// The symbol that means "magnitude too large for this bit-plane, escape".
pub const ESCAPE: i32 = 16;

/// One more than the largest coefficient-pair index [`Contexts`] tracks
