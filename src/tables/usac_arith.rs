/// Map an accumulated context state to a row of [`ARI_CF_M`].
///
/// [`ARI_HASH_M`] holds the handful of context values (out of a 20-bit space)
/// that get their own dedicated model row; everything else falls back to
/// [`ARI_LOOKUP_M`], indexed by where the binary search landed. Both arrays are
/// walked together so a hit returns the dedicated row and a miss still returns
/// something sensible from the neighbourhood.
pub fn context_pk(context: u32) -> usize {
    let mut i_min: i32 = -1;
    let mut i_max: i32 = ARI_HASH_M.len() as i32 - 1;
    while i_max - i_min > 1 {
        let i = i_min + ((i_max - i_min) >> 1);
        let probe = ARI_HASH_M[i as usize];
        if context < probe {
            i_max = i;
        } else if context > probe {
            i_min = i;
        } else {
            return ARI_HASH_M_LSB[i as usize] as usize;
        }
    }
    ARI_LOOKUP_M[i_max as usize] as usize
}

/// The two-dimensional context history a coefficient-pair sequence is coded
/// against: `pres` accumulates this block's decoded magnitudes as coding
/// proceeds (frequency axis), `prev` holds the previous block's magnitudes at
/// the same positions (time axis).
///
/// Shared by the encoder and decoder because the update rules are identical —
/// only which side derives a magnitude from a symbol versus a symbol from a
/// magnitude differs, and that lives in `encoder::usac::arith` /
/// `decoder::usac::arith`.
#[derive(Debug, Clone)]
pub struct Contexts {
    prev: [i32; CONTEXT_LEN],
    pres: [i32; CONTEXT_LEN],
}

impl Contexts {
    /// A freshly reset history, as at a stream's first block.
    pub fn new() -> Self {
        Self { prev: [0; CONTEXT_LEN], pres: [0; CONTEXT_LEN] }
    }

    #[inline]
    fn index(i: isize) -> usize {
        (i + OFFSET) as usize
    }

    /// This block's accumulated magnitude at position `i` (or a guard slot for
    /// `i < 0`).
    #[inline]
    pub fn pres(&self, i: isize) -> i32 {
        self.pres[Self::index(i)]
    }

    /// Record the magnitude coded at position `i`.
    #[inline]
    pub fn set_pres(&mut self, i: isize, value: i32) {
        self.pres[Self::index(i)] = value;
    }

    /// The previous block's magnitude at the same frequency position.
    #[inline]
    pub fn prev(&self, i: isize) -> i32 {
        self.prev[Self::index(i)]
    }

    /// Directly set the previous-block history at `i` (used to seed a
    /// context from a known state, e.g. in tests).
    #[inline]
    pub fn set_prev(&mut self, i: isize, value: i32) {
        self.prev[Self::index(i)] = value;
    }

    /// Slide this block's history into `prev` and reset `pres` to its initial
    /// value of 1, ready for the next block. Coding a block always ends with
    /// this (the encoder after writing it, the decoder before reading it — the
    /// two land on the same state either way since nothing else touches the
    /// arrays between calls).
    pub fn advance(&mut self, len: usize) {
        for i in 0..len as isize {
            self.set_prev(i, self.pres(i));
            self.set_pres(i, 1);
        }
    }

    /// The running per-coefficient context state, folding in the previous
    /// block's magnitude one position ahead and this block's magnitudes just
    /// behind, plus a flag (the `0x10000` addend) for runs of near-silence that
    /// steers escape coding towards a model expecting mostly zeros.
    ///
    /// `state` is threaded through successive calls at `i = 0, 1, 2, ...`
    /// within one block; it is *not* reset per coefficient.
    pub fn get_context(&self, i: usize, state: &mut u32) -> u32 {
        let next_prev = self.prev(i as isize + 1) as u32;
        let mut c = (*state >> 4).wrapping_add(next_prev << 12);
        c = (c & 0xFFF0).wrapping_add(self.pres(i as isize - 1) as u32);
        *state = c;
        if i > 3 {
            let recent = self.pres(i as isize - 1) + self.pres(i as isize - 2) + self.pres(i as isize - 3);
            if recent < 5 {
                return c + 0x10000;
            }
        }
        c
    }

    /// Reset outright, or rescale the history when the block length changes
    /// (a long/short window transition changes how many coefficient pairs a
    /// block covers, and the context arrays are indexed by position within a
    /// block).
    ///
    /// `pres_len` and `prev_len` are full coefficient counts (not pairs), matching
    /// the reference implementation's own units for this call.
    pub fn remap(&mut self, pres_len: usize, prev_len: usize, reset: bool) {
        if reset {
            self.prev = [0; CONTEXT_LEN];
            self.pres = [0; CONTEXT_LEN];
            return;
        }
        if pres_len == prev_len {
            return;
        }
        let saved_prev = self.prev;
        let saved_pres = self.pres;
        let ratio = prev_len as f32 / pres_len as f32;
        for i in 0..pres_len / 2 {
            let k = (i as f32 * ratio) as usize;
            self.prev[2 + i] = saved_prev[2 + k];
            self.pres[2 + i] = saved_pres[2 + k];
        }
        self.prev[pres_len / 2 + 2] = saved_prev[prev_len / 2 + 2];
        self.pres[pres_len / 2 + 3] = saved_pres[prev_len / 2 + 3];
    }
}

impl Default for Contexts {
    fn default() -> Self {
        Self::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The lookup and hash tables must agree on every dedicated context: a hash
    /// hit's row has to be reachable by falling through to the same neighbour
    /// the miss path would have picked, or the two error-prone tables have
    /// drifted apart during porting.
    #[test]
    fn context_pk_never_indexes_past_the_model_table() {
        for &context in ARI_HASH_M.iter() {
            let pki = context_pk(context);
            assert!(pki < ARI_CF_M.len());
        }
        for context in [0u32, 1, 4370, 100_000, 0xFFFFFF] {
            let pki = context_pk(context);
            assert!(pki < ARI_CF_M.len());
        }
    }

    /// Every model row must be a valid (non-increasing, zero-terminated)
    /// cumulative frequency table, or the arithmetic coder's interval math
    /// breaks down silently instead of failing loudly.
    #[test]
    fn cf_m_rows_are_descending_cumulative_tables() {
        for row in ARI_CF_M.iter() {
            assert_eq!(row[row.len() - 1], 0);
            for pair in row.windows(2) {
                assert!(pair[0] >= pair[1]);
            }
            assert!((row[0] as u32) < (1 << 14));
        }
    }

    #[test]
    fn cf_r_rows_are_descending_cumulative_tables() {
        for row in ARI_CF_R.iter() {
            assert_eq!(row[row.len() - 1], 0);
            for pair in row.windows(2) {
                assert!(pair[0] >= pair[1]);
            }
        }
    }

    #[test]
    fn reset_zeroes_both_arrays() {
        let mut ctx = Contexts::new();
        ctx.set_pres(0, 9);
        ctx.set_prev(0, 9);
        ctx.remap(64, 64, true);
        assert_eq!(ctx.pres(0), 0);
        assert_eq!(ctx.prev(0), 0);
    }

    #[test]
    fn same_length_remap_is_a_no_op() {
        let mut ctx = Contexts::new();
        for i in 0..10isize {
            ctx.set_pres(i, i as i32 + 1);
        }
        let before = ctx.pres;
        ctx.remap(512, 512, false);
        assert_eq!(ctx.pres, before);
    }

    /// A halving rescale should pick every other position, exactly the ratio
    /// formula's definition: `k = floor(i * prev_len / pres_len)`.
    #[test]
    fn rescale_follows_the_ratio_formula() {
        let mut ctx = Contexts::new();
        for i in 0..40isize {
            ctx.set_pres(i, i as i32);
        }
        ctx.remap(64, 128, false);
        for i in 0..20isize {
            let k = (i as f32 * 2.0) as isize;
            assert_eq!(ctx.pres(i), k as i32, "position {i}");
        }
    }
}
